#pragma once

#include "../../Const/CheatConst.h"

class CarBase;

//==========================================================
// HjNoClip
//   車ごと飛ばす。自作なので Hj 接頭辞。
//
//   ■ カメラだけ飛ばすのとは違う
//   カメラだけ動かすと、車は元の場所に残る。
//   見に行った先で走り出せないし、多人数のときは
//   相手からは動いていないように見える。
//
//   車そのものを動かせば、着地した所からそのまま走れる。
//
//   ■ 物理は止める
//   動かしている間に物理を回すと、位置を毎フレーム
//   引き戻されて震える。halt で止めてから位置を書く。
//   切ったときに戻す。
//
//   ■ カメラの向きで動く
//   車の向きで動かすと、後ろを向いた瞬間に操作が反転する。
//   見ている方向へ進むほうが迷わない。
//==========================================================
class HjNoClip
{
public:
	// 入っている間、毎フレーム呼ぶ。
	// 切り替わった瞬間に物理の入り切りもここでやる
	void Update(CarBase& car, bool enabled, float dt);

private:
	// 画面のカメラの前・右を取り出す
	static void CameraBasis(Math::Vector3& outFwd, Math::Vector3& outRight);

	// 前フレームで入っていたか。切り替わりを見る
	bool m_prev = false;

	// 入る前の物理の状態。切ったときに戻す
	bool m_haltedBefore = false;
};
