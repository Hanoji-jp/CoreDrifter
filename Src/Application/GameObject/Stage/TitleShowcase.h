#pragma once

#include "../Car/Silvia.h"
#include "../../Const/ShowcaseConst.h"

//==========================================================
// TitleShowcase
//   タイトル画面に置く車の展示。
//
//   タイトルは3Dのシーンを窓抜きで貼る作りになっているが、
//   これまでその中身が空だった。緑一色の空間に車を1台置いて、
//   ゆっくり回して見せる。
//
//   ■ 走行画面とまったく同じ描き方をする
//   Silvia をそのまま継承して、描画は基底のものを使う。
//   自前で描くと、アウトライン・調整パネルで設定した色・車輪の配置を
//   二重に持つことになり、片方だけ直したときに見た目が食い違う。
//   タイトルに映る車は「走行画面と同じ車」でなければ意味がない。
//
//   ■ 走らせない
//   走らせるには地形の読み込みと物理が要る。
//   見せたいのは車であって走行ではないので、物理は止めて、
//   回転台に載せたように向きだけ変える。
//==========================================================
class TitleShowcase : public Silvia
{
public:
	void Init()    override;
	void Update()  override;
	void PreDraw() override;

private:
	// 展示用のカメラ。タイトルには他にカメラがいないので自分で持つ
	std::shared_ptr<KdCamera> m_spCamera;

	// 回転台の角度
	float m_turn = 0.0f;
};
