//==========================================================
// HjModLoader
//   差し替えモデルの安全な読み込み。自作なので Hj 接頭辞。
//
//   ■ なぜ専用の入口が要るか
//   フレームワークの読み込みは、失敗すると assert で止まる。
//   標準のモデルは必ず在ることが分かっているのでそれでよいが、
//   MODは利用者が置いたファイルなので、
//   壊れている・消された・別物だった、が普通に起きる。
//   そのまま渡すとゲームごと落ちる。
//
//   ■ 二段で見る
//   読み込む前  … 在るか、形式が合うか、大きすぎないか
//   読み込んだ後… 中身が重すぎないか(点数・部品数)
//
//   前だけでは足りない。容量が小さくても、
//   点を極端に多く書いたデータは作れるため。
//==========================================================
class HjModLoader
{
public:
	// 読み込めなかった理由。画面へそのまま出す。
	// 「読めません」だけだと、置き場所が違うのか、
	// 形式が違うのか、重すぎるのか分からず、直しようがない
	enum class Result
	{
		Ok,
		NotFound,     // ファイルが無い(消された・名前が変わった)
		BadFormat,    // .gltf / .glb ではない
		TooLarge,     // 容量の上限を超えている
		LoadFailed,   // 形式は合っているが、中身が壊れている
		TooHeavy,     // 読めたが、点数か部品数が多すぎる
	};

	// path のモデルを work へ読み込む。
	// 失敗したときは work を触らない(前の見た目のまま残る)。
	//
	// ※ path が空、または「標準」の印なら Ok を返して何もしない。
	//   呼び側で分岐させると、その判定が各所に散る
	static Result Load(KdModelWork& work, const std::string& path);

	// 理由を日本語にして返す。画面へそのまま出せる
	static const char* Message(Result r);

private:
	// 読み込む前に見る。ここを通ったものだけをローダへ渡す
	static Result PreCheck(const std::string& path);

	// 読み込んだ後に見る。点数と部品数が上限に収まっているか
	static bool IsWithinBudget(const KdModelWork& work);
};
