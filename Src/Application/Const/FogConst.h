#pragma once

// 距離フォグの定数。
//
// シェーダー側の計算は f = saturate(1/exp(距離×Density))、
// 出力色 = lerp(FogColor, 元の色, f)。
// つまり距離0でf=1(元の色そのまま)、遠いほどfog色へ寄っていく。
namespace FogConst
{
	// フォグの色。空や地形の色から浮かないよう、彩度を落とした中間の灰色にする。
	// 派手な色を付けると、遠くの山だけ別の絵に見えてしまう。
	constexpr float ColorR = 0.56f, ColorG = 0.60f, ColorB = 0.66f;

	// 減衰率。値を大きくするほど早く色が抜ける。
	//   0.0025 … 300m先でおよそ半分、700m先でほぼ完全にフォグ色
	// 峠コースは遠くの稜線まで見渡せるマップなので、近くの視認性を保ったまま
	// 奥行きだけ出るよう、控えめな値にしてある。
	constexpr float Density = 0.0025f;

	// 高さフォグは使わない(コースの高低差ぶんだけ帯が動いて不自然になりやすいため)。
	// 距離フォグだけで奥行きを付ける。
}
