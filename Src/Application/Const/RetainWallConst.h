#pragma once

// 山側の擁壁(コンクリートの壁)の定数。
//
// ■ どこに置くかが本体
// ガードレールの鏡像。あちらは「道の縁の外の地形が落ちていたら置く」で、
// こちらは「上がっていたら置く」。
//
// 実際の峠も、切り通しになっている所にだけ擁壁がある。
// 平場や盛り土の所に立てると、支える土が無いのに壁だけある絵になる。
//
// ■ 形は道と同じ仕掛け
// 断面を刻みごとに並べて押し出す。道の刻みの決め方(曲がりに合わせる)と
// 断面の向き(ミター)をそのまま借りるので、ヘアピンでも破綻しない。
//
// ■ 当たり判定は持たない
// 将来すべて剛体で処理する方針。ここで簡易な壁を入れると二重になる。
namespace RetainWallConst
{
	//===== どこに置くか =====
	// 道の中心からこの距離に壁を立てる。
	// ガードレールと同じ値にしてあるので、片側が壁・片側が柵になる
	constexpr float Offset = 5.4f;

	// 壁の位置から更に外を見て、地形の高さを測る。
	// 壁のすぐ上だと、道が削った法面そのものを測ってしまう
	constexpr float LookOut = 6.0f;

	// 路面よりこれだけ上がっていたら擁壁。
	// 小さくすると、わずかな起伏で壁が立ち続ける
	constexpr float RiseThreshold = 2.0f;

	//===== 走りの整理 =====
	// 数メートルだけの擁壁は現実にも無いし、見た目も悪い。
	// 先に切れ目を埋めてから、短い区間を落とす
	constexpr float MinRun = 14.0f;
	constexpr float MaxGap = 18.0f;

	//===== 壁の形 =====
	// 高さの下限と上限(m)。
	//
	// 上限を超えたぶんは自然の斜面のまま残す。
	// 実際の峠も、擁壁は下の数メートルだけで、その上は法面
	constexpr float MinHeight = 1.6f;
	constexpr float MaxHeight = 8.0f;

	// 走りの切れ目と見なす高さ(m)。
	//
	// 以前は MinHeight の半分(0.8m)で切っていたので、
	// 高さが滑らかに落ちていっても 0.8m の所で唐突に終わり、
	// 厚みの無い縁が切り口として見えていた。
	//
	// ほぼ 0 まで引っ張れば、壁が地面へ沈んで消える
	constexpr float RunEpsilon = 0.03f;

	// 根元を路面より下へ埋める量(m)。
	// ちょうどに置くと、路肩の細かい起伏で下端が浮く
	constexpr float FootSink = 0.35f;

	// 上へ行くほど山側へ倒す量(高さに対する割合)。
	// 垂直だと板に見える。実物も 1:0.3 ほど傾いている
	constexpr float Batter = 0.16f;

	//===== 目地(パネルの継ぎ目) =====
	// 段の高さ(m)。この間隔で横一文字の溝が入る
	constexpr float PanelH = 2.0f;

	// 段を何段まで持つか。MaxHeight / PanelH ぶん。
	//
	// 段数は刻みごとに変えない。変えると、隣り合う刻みで
	// 断面の点の数が違ってしまい、帯として繋げなくなる。
	// 壁が低い所では、上の段を天端へ潰して畳む
	constexpr int MaxRows = 4;

	// 溝の深さ(m)と幅(m)。
	// 深くしすぎると穴に見える。輪郭の後処理が線を拾うので、
	// これくらいでも十分に目地として読める
	constexpr float JointDepth = 0.045f;
	constexpr float JointHalf  = 0.035f;

	//===== 笠石(天端の張り出し) =====
	// 道側へ張り出す量(m)と、その厚み(m)。
	// これが無いと、ただの壁で終わって構造物に見えない
	constexpr float CopingOut = 0.13f;
	constexpr float CopingH   = 0.22f;

	//===== 天端(壁の上の床) =====
	// 笠石の上から山側へ水平に伸ばす幅(m)。
	//
	// これが無いと、壁の一番上で面が終わって断面が開く。
	// 上から覗くと壁の中が見えるし、輪郭も途中で切れる。
	//
	// 実際の擁壁も天端は平らな床になっていて、その先から法面が続く。
	// 山が高い所ではこの床は土に埋まって見えなくなる(それでよい)
	// 実物の天端は人が歩ける幅がある。
	// 狭いと、壁の上に細い縁があるだけに見えて棚に見えない
	constexpr float TopReach = 2.4f;

	//===== 色 =====
	// コンクリートは白くない。空の色を反射して薄い灰になる
	constexpr float WallR = 0.55f, WallG = 0.55f, WallB = 0.53f;
	constexpr float CopeR = 0.62f, CopeG = 0.62f, CopeB = 0.60f;

	// 刻みごとの色の振れ幅。
	// 全部同じだと、数百メートルの1枚板に見える
	constexpr float Vary = 0.06f;
}
