#pragma once

// 剛体の車の定数。
//
// ■ ここにあるのは「車体とサス」だけ
// タイヤの摩擦・駆動・操舵は旧モデル(CarBase)の調整値をそのまま使う。
// 両方に持つと、調整パネルを触っても片方しか変わらない。
//
// ■ 力で書く
// 旧モデルは加速度で組まれていて質量を持っていなかった。
// こちらは力を積むので、単位が違う。持ってきても合わない
namespace RigidCarConst
{
	//===== 車体 =====
	// FRのスポーツクーペ。車検証に載る値の範囲
	constexpr float Mass = 1250.0f;   // kg

	// 慣性を出すための箱の寸法(m)。全幅・全高・全長の半分
	constexpr float HalfW = 0.85f;
	constexpr float HalfH = 0.62f;
	constexpr float HalfL = 2.25f;

	// 重心の高さ(接地面から, m)。
	//
	// ここが高いほどロールしやすく、転びやすい。
	// スポーツカーは低く、0.45〜0.55 あたり
	constexpr float CgHeight = 0.50f;

	// 重心の前後位置。0=車体中央、正=前寄り(m)。
	// FRは前寄りだが、重量配分を50:50に近づけてある車が多い
	constexpr float CgOffsetZ = 0.05f;

	//===== サスペンション =====
	// レイを飛ばす長さ(m)。伸びきりから縮みきりまで
	constexpr float SuspRest   = 0.38f;   // 自然長
	constexpr float SuspTravel = 0.20f;   // 縮み代

	// ばね定数(N/m)。
	//
	// 静止時に自然長からどれだけ沈むかで決める。
	// 1輪あたり約 3060N を受けて 6cm 沈む設定
	constexpr float SpringF = 52000.0f;
	constexpr float SpringR = 48000.0f;

	// 減衰(N per m/s)。
	//
	// 小さいと跳ね続け、大きいと路面に吸い付いて動かない。
	// 臨界減衰の 0.3〜0.5 倍あたりが車らしい
	constexpr float DamperF = 4200.0f;
	constexpr float DamperR = 3900.0f;

	// スタビライザ(N/m)。左右の沈み込みの差に効く。
	// 前を強くするとアンダー、後ろを強くするとオーバーに寄る
	constexpr float ArbF = 14000.0f;
	constexpr float ArbR = 9000.0f;

	//===== 底付き =====
	// 縮み代を使い切った先で当たるゴム(バンプラバー)。
	//
	// ■ 無いと坂で減速しない
	// 底付きした先は、位置を押し出して直すしかなくなる。
	// 押し出しは力ではないのでエネルギーを奪わない。
	// 高速で急斜面へ突っ込んでも速度が落ちず、
	// 本来なら途中で失速するはずの坂を登り切ってしまう。
	//
	// 実車もゴムが当たって急に硬くなる。通常のばねより一桁硬い
	constexpr float BumpStop = 600000.0f;   // N/m
	constexpr float BumpDamp = 24000.0f;    // N per m/s

	// ゴムが潰れきる量(m)。
	//
	// ここまではゴムが力で受け止める。超えた先だけ位置で押し出す。
	// 押し出しを先に効かせると、ゴムが仕事をする前にめり込みが
	// 消えてしまい、衝撃を吸う役が誰も居なくなる
	constexpr float BumpMax = 0.06f;
	
	//===== タイヤ =====
	// 当たりを取るための半径(m)。
	//
	// 見た目の車輪(m_wheelH)とは別。あちらはモデルに合わせて
	// 車ごとに変わるので、接地の計算に混ぜると車ごとに
	// 車高が変わってしまう
	constexpr float WheelRadius = 0.33f;

	// 接地を探す長さ(m)。
	//
	// サス上端から接地点までは「自然長 + タイヤ半径」ある。
	// タイヤ半径を足し忘れると、静止状態でもレイが地面に届かず、
	// 接地なしと判定されて自由落下する。
	// 落ちて深くめり込むと底付きで打ち上げられ、永久に跳ねる。
	//
	// 式で書いておく。定数を触っても崩れない
	constexpr float ProbeLen = SuspRest + WheelRadius;

	//===== 床を探す =====
	// サスの向きへ刻んで進める回数と、そのあと詰める回数。
	//
	// 真下へ引くだけでは、車体が傾いたときに沈み込みの測り方がずれる。
	// サスは車体の下方向に沿って動くので、そちらへ飛ばす。
	//
	// 見る長さは 0.7m 程度なので、刻みは少なくてよい
	constexpr int ProbeSteps  = 6;
	constexpr int ProbeRefine = 6;

	//===== 世界の外 =====
	// 地形より下へこれだけ落ちたら、落下と見なして戻す。
	// 拾わないと、地図の外へ出た車が永久に落ち続ける
	constexpr float FallLimit = 200.0f;

	//===== 空中 =====
	// 接地している輪が1つも無いときの、回転の減衰(1/s)。
	//
	// これは物理ではない。空中の車は空気抵抗しか受けないので、
	// 本当は回り続ける。
	//
	// ただし跳ねた瞬間の回転がそのまま残ると、着地の向きが
	// 運任せになって遊べない。時定数3秒ほどの弱い減衰に留める
	constexpr float AirAngDamp = 0.6f;

	//===== 刻み =====
	// 刻みの上限(秒)。
	//
	// バネは刻みが粗いと発散する。1フレームが長いときは
	// 中で分割して解く
	constexpr float MaxStep = 1.0f / 120.0f;
	constexpr int   MaxSubSteps = 8;

	//===== 転倒からの復帰 =====
	// 上向きがこれより下を向いたら転倒と見なす
	constexpr float FlipUpDot = -0.2f;

	// 転倒したまま何秒でリセットするか
	constexpr float FlipResetTime = 3.0f;
}
