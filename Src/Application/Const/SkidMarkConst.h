#pragma once

// 路面に残るタイヤ痕(スキッドマーク)の定数。
// 後輪の接地点を追いかけて点を打ち、隣り合う点の間を帯(四角形)で繋いで1本の痕にする。
namespace SkidMarkConst
{
	// 痕の本数。0,1=後輪の左右 / 2,3=前輪の左右
	// ── 焼き付け方式(マークマップ) ──
	// コース全体を真上から見た1枚のテクスチャに痕を「書き溜める」。
	// クリアしないので書いたものはずっと残り、毎フレーム描くのは
	// 「新しく増えた数センチぶん」だけで済む＝何本走っても重くならない。
	// 路面側はこのテクスチャをワールドXZで引いて色を暗くするだけ。
	//
	// 帯を毎フレーム全部組み立て直す従来方式と違い、
	//   ・痕の長さが無制限(1周ぶん残せる)
	//   ・坂やバンクでも路面に完全密着する(浮き・埋まり・Zファイティングが原理的に無い)
	constexpr bool BakeToMap = true;

	// マップはコース全体ではなく「カメラの周りだけ」を覆い、一緒にスクロールさせる。
	// コース全体を1枚で覆うと、広いコースほど1ドットが受け持つ実寸が大きくなり、
	// 痕の幅(24cm)がドットを下回って点線になったりボケたりする。
	// 覆う範囲を絞れば、コースがどれだけ広くても解像度は一定に保てる。
	// 痕が残る距離は「覆う範囲の半分」。狭いとすぐ消えてしまうので、
	// 鮮明さ(1ドットの実寸)と残る距離のバランスで決める。
	//   6144ドットで240m → 3.9cm/ドット。痕の幅(24cm)は約6ドットぶんで十分鮮明、
	//   かつ半径120mまで残る。メモリは1チャンネルなので36MB×2枚。
	constexpr int   MapResolution = 6144;
	constexpr float MapCoverage   = 240.0f;

	// カメラが窓の中心からこれだけ離れたら窓を動かす(m)。
	// 動かす時は前の内容をずらして写し、はみ出た側は空になる。
	// 小さいほど滑らかだが写す回数が増える。窓の半分(120m)より十分小さくすること。
	constexpr float MapRecenterDist = 30.0f;

	// 窓の縁で痕を消していく幅(0〜1。1が窓の端)。
	// 何もしないと窓の境界で痕がぶつ切りになるので、手前から薄くして誤魔化す。
	constexpr float MapEdgeFadeStart = 0.80f;

	// 焼き込む帯の最低幅(ドット単位)。これを下回る細さで焼くと点線になるので、
	// 解像度が足りない時は実寸より少し太らせてでも線を繋ぐ。
	constexpr float MapMinTexelWidth = 2.5f;
	// 路面をどこまで暗くするか(1=真っ黒)。焼き付けは重ね書きで濃くなっていく
	// 画面全体のハーフトーンは「暗い所ほど網点を強く出す」ので、痕を黒くしすぎると
	// そこだけ網点が最大で出て砂を撒いたようなノイズに見える。
	// 路面より少し暗い程度に留めるのがちょうどよい。
	constexpr float MapDarken = 0.42f;

	constexpr int TrailCount = 4;
	// 1本あたりの点の上限。点は「一定距離進むごと」に打つので、
	// MaxPoints * MinSegLen がおおよその痕の最大長になる。
	constexpr int MaxPoints = 400;

	// 点を打つ最小間隔(m)。細かすぎると点が増えて重く、粗すぎるとカーブがカクつく
	constexpr float MinSegLen = 0.14f;
	constexpr float Width     = 0.24f;  // 痕の幅(m)。タイヤの接地幅に合わせる

	// 路面へのめり込み・Zファイティング対策の浮かせ量(m)。
	// 大きすぎると坂で痕が浮いて見えるので最小限に。
	constexpr float GroundOffset = 0.015f;

	// 消え方：しばらく濃いまま残り、後半で薄れて消える
	constexpr float Lifetime  = 7.0f;   // 点が消えるまでの時間(秒)
	constexpr float FadeStart = 0.55f;  // この寿命比までは濃さを保つ

	// スリップが弱いと薄く、強いと濃く。0〜1のスリップ量に掛ける
	constexpr float AlphaMax   = 0.62f; // 最大の濃さ
	constexpr float SlipMinFor = 0.15f; // これ未満のスリップ量では痕を残さない

	// 前輪：舵を切った向きに対して横へ滑っている量(タイヤ座標系の横速度)で判定する。
	// 駆動しない前輪は空転しないので、後輪と違って横滑りだけが摩擦痕になる。
	constexpr float FrontSlipThreshold = 2.2f;  // これ以上の横滑り(m/s)で痕が出始める
	constexpr float FrontSlipFull      = 7.0f;  // これで最大の濃さ
	constexpr float FrontAlphaMul      = 0.75f; // 前輪は後輪より薄く(ロックしないため)
	constexpr float FrontWidthMul      = 0.90f; // 前輪は接地幅がやや狭い

	// 色(黒に近い焦げ茶。真っ黒だとアスファルトに馴染まず浮く)
	constexpr float ColorR = 0.07f, ColorG = 0.06f, ColorB = 0.06f;
}
