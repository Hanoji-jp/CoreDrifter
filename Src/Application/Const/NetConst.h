#pragma once

// マルチプレイ(P2P)の定数。
//
// ■ 方針
// ルーム画面は本番の見た目で作り、中身は当面「直接IP」で繋ぐ。
// マッチングサーバーは常時稼働のサーバーが要るので今は用意しない。
// あとで差し替えられるよう、通信の口(HjNetTransport)を1枚挟んである。
//
// ■ 何を送るか
// 送るのは「車の状態」だけで、煙やタイヤ痕そのものは送らない。
// 粒を一つずつ送ると帯域がいくらあっても足りないうえ、遅延で
// 出る場所がずれる。滑り量とタイヤの位置さえ届けば、演出は
// 各PCが自分で作れる。タイヤ痕は元々1枚の共有マップへ焼く作りなので、
// 他人の車のぶんを同じ仕組みへ流し込むだけで済む。
namespace NetConst
{
	//===== 接続 =====
	constexpr unsigned short DefaultPort = 50721;   // ホストが待ち受けるポート
	constexpr int   MaxPlayers   = 4;               // 自分を含む上限
	constexpr int   MaxPacket    = 512;             // 1パケットの上限(バイト)

	// 位置を送る回数(毎秒)。
	// 上げるほど滑らかになるが帯域を食う。届かなかったぶんは補間で埋めるので、
	// 描画のフレームレートまで上げる必要はない。
	constexpr float SendRate     = 20.0f;

	// 補間のためにわざと遅らせて表示する時間(秒)。
	// 届いた最新の位置をそのまま描くと、パケットが1つ遅れただけで
	// 相手の車が止まって見え、次で飛ぶ。少し過去を描くことで、
	// 手元に常に「次の位置」がある状態にして繋いで見せる。
	constexpr float InterpDelay  = 0.12f;

	//===== 相手の時計に合わせる =====
	// 届いた時刻で並べてはいけない。
	//
	// 送り主は一定の間隔で送っているが、届く間隔は回線の都合でばらつく。
	// 受け取った時刻で並べると、そのばらつきがそのままデータに焼き付き、
	// 区間ごとに速さが変わって見える(がくがくする)。
	//
	// 連番から送信時刻を組み直せば、間隔は必ず一定になる。
	//   送信時刻 = 連番 ÷ 毎秒の回数
	//
	// あとは、その時計と自分の時計のずれを1つ覚えておけばよい。

	// ずれを寄せる速さ(1パケットあたりの割合)。
	// 時計は少しずつずれるので合わせ続ける必要があるが、
	// 急に合わせると、その瞬間に相手の車が飛ぶ
	constexpr float ClockBlend = 0.02f;

	// これ以上ずれていたら、寄せずに合わせ直す。
	// 相手が入り直して連番が0から振り直された場合や、
	// 長く止まっていた場合は、少しずつ寄せていては追いつかない
	constexpr float ClockResync = 0.5f;

	// この秒数だけ何も届かなければ切断とみなす。
	// UDPは切断を教えてくれないので、沈黙している時間で判断するしかない
	constexpr float Timeout      = 5.0f;

	// 1フレームに取り出すパケットの上限。
	// 上限が無いと、大量に届いたときにここでフレームを使い切ってしまう
	constexpr int   RecvPerFrame = 64;

	// 受け取った状態を貯めておける上限。
	// シーンが取り出さないまま増え続けないようにする。位置の同期は
	// 「次が来れば古いものは要らない」ので、あふれたら古いほうから捨ててよい
	constexpr int   InboxMax     = 128;

	// 接続要求を送り直す間隔(秒)。UDPは届かないことがあるので繰り返す
	constexpr float JoinRetry    = 0.5f;

	//===== 他人の車を描くための補間 =====
	// 手元に残しておく過去の状態の数。
	// InterpDelay ぶんの過去を描くので、その時間を挟める数があればよい。
	// 20Hz・0.12秒なら3個で足りるが、届き方がばらつくので余裕を持たせる
	constexpr int   HistoryMax   = 32;

	// 最新より先を描かざるを得なくなったとき、速度から伸ばしてよい秒数。
	// パケットが途切れたとき、その場で止めると相手の車がカクッと止まり、
	// 復帰した瞬間に飛ぶ。少しだけ伸ばして繋ぐ。
	// 伸ばしすぎると壁を突き抜けた位置を描いてしまうので短くする
	constexpr float ExtrapolateMax = 0.25f;

	//===== 名前 =====
	constexpr int   MaxNameLen   = 15;   // 終端を除いた最大文字数
}
