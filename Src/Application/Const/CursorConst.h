#pragma once

#include "../GameObject/UI/UIConst.h"

// 自前で描くマウスポインタの定数。
//
// ■ なぜ自分で描くか
// OSのカーソルはWindowsの見た目そのままで、この作品のUIから浮く。
//
// ■ 塗りのある矢印に、硬い影を落とす
// 照準(十字)は狙いを定める道具に見えて、メニューには強すぎた。
// 輪郭だけの線画は下が透ける代わりに、細くて存在感が無かった。
//
// この画面のUIは、板を置いてその下にずらした影を敷く作りで揃えてある
// (チップ・銘板・タブ)。ポインタも同じ組み方にする。
//   影(墨・ずらす) → 本体(アシッド緑・塗り) → 縁(墨・細い線)
// 塗りで面積が出て、影で紙から浮き、縁で背景から切り離される。
//
// ■ 先端が指す位置
// 矢印は先端で指すものなので、カーソル座標を先端に合わせる。
// 中心に合わせると、指しているつもりの場所と実際がずれる。
namespace CursorConst
{
	//===== 形(デザインpx。先端を原点とした相対座標) =====
	// 右下へ向く矢印。Windowsのものより細く鋭くして、
	// 計測器のような画面に馴染ませる。
	//   先端 → 左辺を下へ → 尾の付け根 → 尾 → 右肩 → 先端へ戻る
	constexpr float Shape[] =
	{
		 0.0f,  0.0f,   // 先端(ここがカーソル位置)
		 0.0f, 17.5f,   // 左辺の下端
		 4.6f, 13.2f,   // 尾の付け根(内側へ切れ込む)
		 7.6f, 20.0f,   // 尾の先(左)
		10.6f, 18.6f,   // 尾の先(右)
		 7.6f, 12.0f,   // 尾の付け根へ戻る
		12.6f,  9.6f,   // 右肩
	};
	constexpr int ShapePointCount = static_cast<int>(std::size(Shape)) / 2;

	//===== 影 =====
	// ずらして敷く硬い影。ぼかさないのは、UIの他の要素と揃えるため
	constexpr float ShadowOffD = 2.2f;

	//===== 縁 =====
	// 塗りだけだと背景に溶けるので、細い墨で切り離す
	constexpr float EdgePx = 1.4f;

	//===== 動かしていないときは消す =====
	// 走行中はキーボードで操作するので、ポインタは邪魔にしかならない。
	// ただし消えたままだとメニューで困るので、動かせば戻る。
	constexpr float IdleHideTime = 2.0f;   // 静止してこの秒数で消え始める
	constexpr float FadeTime     = 0.35f;  // 消えきるまでの時間

	//===== 押している間の反応 =====
	// クリックが効いたかどうかは、押した瞬間に形が変わると分かる
	constexpr float PressScale = 0.88f;   // 押している間の縮小率

	//===== 色 =====
	const Math::Color Fill   = UIConst::ACID;   // 本体(アシッド緑)
	const Math::Color Edge   = UIConst::INK;    // 縁(墨)
	const Math::Color Shadow = UIConst::INK;    // 影(墨)
	constexpr float   ShadowAlpha = 0.45f;
}
