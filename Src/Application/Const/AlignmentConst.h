#pragma once

// アライメント / サスセッティングの定数(CarX風チューニング)
//   タイヤの向き(トー・アッカーマン)、傾き(キャンバー)、前後ロール剛性(スプリング+スタビ)を
//   実挙動へ効かせるためのパラメータ。既定値は「現状の挙動を変えない中立値」にしてある。
//   ※キャスター角/KPI/スクラブ半径は、FFBハンドルが無いと体感・検証できないため未採用。
namespace AlignmentConst
{
	//===== トー角(rad)：真上から見たタイヤの向き。正=トーイン / 負=トーアウト =====
	// フロントtoe-outで切り始めの反応UP(ドリフトの入り)、リアtoe-inで直進安定。
	constexpr float ToeFront = 0.0f;   // 0=まっすぐ(現状)
	constexpr float ToeRear  = 0.0f;

	//===== アッカーマン(-1〜1)：左右前輪の切れ角差 =====
	//   0 = 左右平行(現状)。正 = イン側が多く切れる(通常車)。負 = アウト側が多く切れる(アンチ、ドリフト向き)。
	constexpr float Ackermann = 0.0f;

	//===== キャンバーの横グリップ寄与 =====
	//   0 = 見た目だけ(現状)。正で、ネガキャン(|camber|)に応じて横グリップが増す。
	constexpr float CamberGrip = 0.0f;

	//===== 前後ロール剛性(スプリングレート + スタビライザー) =====
	//   横方向の荷重移動を前後どちらへ多く分けるかを決める＝アンダー/オーバーの調整。
	//   フロントを固めるとフロント荷重移動大→フロントが逃げてアンダー。
	//   リアを固めるとリアが逃げてオーバー(お尻が出る)。既定は前後同じ=中立(現状の50:50)。
	constexpr float SpringFront = 1.0f;   // フロントばね定数(相対値)
	constexpr float SpringRear  = 1.0f;   // リアばね定数(相対値)
	constexpr float ArbFront    = 0.0f;   // フロントスタビ(相対値, ロール剛性に加算)
	constexpr float ArbRear     = 0.0f;   // リアスタビ(相対値)
}
