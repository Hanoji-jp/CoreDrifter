#pragma once

// 高さマップで作る地形の定数。
//
// ■ なぜモデルではなく高さマップか
// 峠の山肌を手でモデリングするのは無理がある。
// 実測の標高データ(DEM)を1枚の画像として持てば、そのまま地形になる。
//
// ■ 当たり判定が軽くなる
// いままでは地形のメッシュへ光線を飛ばしていた。
// コースが数千の部品でできているので、1回が高い。
//
// 高さマップなら、位置から直接どのマス目かが分かる。
// 4点読んで混ぜるだけで高さが出る。探す必要がない。
//
// これはサスペンションを入れるときに効いてくる。
// サスは4輪ぶんを細かい刻みで解くので、
// 1フレームに数十回の接地判定が要る。光線では持たない。
//
// ■ 頂点はCPUで組む
// 頂点シェーダーで持ち上げる作りもあるが、採らない。
// GPUの補間とC++の補間は細部が一致せず、
// 「見えている地面」と「当たる地面」がずれる。
// 場所によって車が少し埋まる・浮くという、追いにくいバグになる。
//
// 同じ関数から頂点も当たり判定も作れば、ずれようがない。
namespace TerrainConst
{
	//===== 使うかどうか =====
	// true にすると、借りてきた峠のモデルの代わりに
	// 高さマップの地形で走る。
	//
	// 峠を自作へ差し替えるまでの間、両方を残しておく。
	// 片方を消すと、地形が形になるまで走れる場所が無くなる
	// ※借りてきた峠(bushido peak)は Burnout Dominator からの
	//   吸い出しだったので配布できない。地形はこちらで作る
	constexpr bool UseTerrain = true;

	//===== 標高データを使うか =====
	// false にすると平らな地面になる。
	//
	// 実測の標高は起伏が大きすぎて、道を引く邪魔になる。
	// まず平地で道の形を決めて、地面の起伏は後から足す。
	//
	// 道の仕組みは地形があってもなくても同じなので、
	// あとで true に戻せばそのまま乗る
	constexpr bool UseHeightData = false;

	// 平らにするときの標高(m)
	constexpr float FlatHeight = 0.0f;

	//===== 置き場所 =====
	// 高さマップの画像。白いほど高い
	// 標高データ。実数をそのまま並べた形。
	//
	// 画像にしないのは、8bitでは標高400mを256段に潰すことになり、
	// 1.5m刻みになるため。車が乗る地面としては粗すぎる。
	//
	//   int32   幅
	//   int32   高さ
	//   float32 1マスの間隔(m)
	//   float32 高さ …… 北西から東へ、行ごとに南下
	constexpr const char* HeightPath = "Asset/Data/terrain/height.r32";

	//===== 切り出し =====
	// 標高データは実測の範囲そのままなので、11km四方ある。
	// 全部を格子とメッシュにすると、まとまりが5000個を超えて
	// 読み込みにも描画にも耐えない。
	//
	// 峠として走るのは1〜2km。使う所だけ切り出す。
	//
	// 中心はデータの中央からのずれ(m)。東と南が正
	constexpr bool  UseCrop   = false;
	constexpr float CropCenterX = 0.0f;
	constexpr float CropCenterZ = 0.0f;

	// 一辺の長さ(m)。2000で約2km四方
	constexpr float CropSize = 2000.0f;

	//===== 大きさ =====
	// マス目1つの間隔(m)。
	// 国土地理院の5mメッシュをそのまま使うなら5.0
	constexpr float CellSize = 5.0f;

	// 画像の明るさ(0〜1)を標高(m)へ直す幅。
	//   標高 = 明るさ * HeightScale + HeightBase
	// 実データを入れるときは、その区間の最低標高と標高差を入れる
	constexpr float HeightScale = 400.0f;
	constexpr float HeightBase  = 0.0f;

	//===== 描画の分割 =====
	// 1つのまとまり(チャンク)の1辺のマス目数。
	//
	// 大きいと描画の命令は減るが、画面外を切る単位も大きくなり、
	// 見えていない所まで描くことになる。
	// 小さいと切りやすいが、命令の数が増える。
	// 地形を1mにしたぶん、まとまりを大きくして個数を抑える。
	//
	// 32のままだと1.5km四方で約2200個になり、
	// 頂点バッファの数だけで描画が詰まる。
	// 64なら約550個。1個が重くなるが、まとめて捨てられる
	constexpr int ChunkCells = 64;

	//===== 仮の地形 =====
	// 実データが無いときに作る山。
	// これで「車が地面に乗るか」を先に確かめる
	constexpr int   TestSize   = 257;    // 1辺のマス目数
	constexpr float TestHeight = 90.0f;  // 山の高さ(m)

	// 谷の底の幅(マス目)。ここを道が通る想定で、平らにしておく。
	// 山だけだと、車を置ける平らな所が無くて試せない
	constexpr float TestFlatCells = 6.0f;

	//===== カリング =====
	// 画面に映るまとまりだけ描く。
	//
	// false にすると全部描く。切り方が合っているかを確かめるとき、
	// 「消えているのが正しいのか、判定が壊れているのか」を
	// 切り分けるために要る
	constexpr bool UseCulling = false;

	//===== 色 =====
	// 素材を貼るまでの仮の色。
	// 既定のままだと真っ白で、起伏があるのか分からない。
	//
	// 塗り分け(草・岩)は後の工程なので、いまは1色。
	// 影と法線だけで形が読める程度の明るさにする
	constexpr float GroundR = 0.30f;
	constexpr float GroundG = 0.34f;
	constexpr float GroundB = 0.22f;

	//===== 法線 =====
	// 斜面の向きを求めるときの、隣を見る距離(マス目)。
	// 1にすると細かい凹凸を拾いすぎて、車が細かく揺れる
	constexpr float NormalStep = 1.0f;

	//===== 当たり判定 =====
	// 地形の外を指されたときに返す高さ。
	// 落ちたことが分かるよう、十分低くしておく
	constexpr float OutsideHeight = -10000.0f;
}
