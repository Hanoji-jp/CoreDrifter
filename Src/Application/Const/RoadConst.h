#pragma once

// スプラインで作る道の定数。
//
// ■ なぜ地形と別に持つか
// 高さマップは真上から見た一枚の格子なので、
// 幅6mの道の断面(カントや中央の盛り上がり)を表現できない。
// 5mメッシュを1mへ上げても足りない。
//
// ドリフトではカントが効くので、そこが潰れるのは痛い。
//
// ■ 当たり判定はメッシュを見ない
// 位置をスプラインへ投影すれば、道のどこを走っているかが出る。
// そこから断面を評価すれば、高さと法線が厳密に求まる。
//
// 面を1枚ずつ調べるより速く、しかも正確。
// サスペンションを入れたときに、この差が効いてくる。
namespace RoadConst
{
	//===== 形 =====
	// 路面の幅(m)。片側の半分。全幅はこの2倍
	constexpr float HalfWidth = 3.5f;

	// 路肩の幅(m)。路面の外側に付ける、少し落ちた面。
	// ここまでは走れるが、グリップが落ちる想定
	constexpr float ShoulderWidth = 1.2f;
	// 路肩の落ち込み(m)
	constexpr float ShoulderDrop = 0.12f;

	// 路面中央の盛り上がり(m)。水はけのための形。
	// 少しでも入れると、轍に沿う感じが出る
	constexpr float Crown = 0.05f;

	//===== エプロン(地形へ溶ける裾) =====
	// 道の外側へ広げる面。
	//
	// ■ なぜ要るか
	// 地形は格子(1m四方)で、道は曲がった帯。格子は道の縁に沿えないので、
	// 地形だけで道の境目を作ると、必ず階段状になる。
	// どれだけ削り方を工夫しても、格子である限り消えない。
	//
	// 道からメッシュを生やせば、境目がスプラインの縁になる。
	// 曲がりに沿うので滑らかで、外端の高さを地形へ合わせれば繋がる。
	//
	// ■ 何をしているか
	// 路肩の外から、地形の高さへ向けて降りていく面を張る。
	// 内側は路面の縁の高さ、外側は地形そのものの高さ。
	// 見える境目は、格子ではなくこの面の外端になる。

	// エプロンの幅(m)。路肩の外端からの距離。
	// 広いほど滑らかに溶けるが、道が太って見える
	constexpr float ApronWidth = 7.0f;

	// 幅方向の分割数。
	//
	// 地形の起伏を拾うので、粗いと外端が地形から浮く。
	// 地形が1mマスなので、7mの裾なら7分割では足りない
	constexpr int   ApronSegments = 14;

	// 外端をどれだけ地形へ埋めるか(m)。
	// ちょうどに合わせると、どちらが手前か決まらずちらつく。
	// わずかに沈めれば、地形が確実に上に来る
	constexpr float ApronSink = 0.04f;

	//===== ヘアピン =====
	// 曲がりがきつい所では、内側の断面が前後で追い越して
	// 面が折り返す。半径が道の幅より小さくなるとそうなる。
	//
	// 内側の幅を、その場所の半径より内へ収める。
	// 道が少し細くなるが、折り返すよりはよい。
	//
	// 実際の峠も、ヘアピンでは内側が詰まって見える

	// 半径に対して、内側をどこまで使ってよいか。
	// 1.0だと半径ちょうどで、そこが1点に潰れる
	constexpr float InnerLimitRatio = 0.62f;

	// これより緩い曲がりでは絞らない(1メートルあたりのラジアン)。
	// 半径にすると約100m。普通のコーナーでは効かせない
	constexpr float CurveIgnore = 0.006f;

	//===== 刻み =====
	// スプラインを何メートルごとに分けてメッシュにするか。
	//
	// 細かいほど滑らかだが、頂点が増える。
	//
	// これは地形を削る刻みでもある。粗いと、点と点の間で
	// 削る強さが変わって、道に沿った波になる。
	// 地形のマス目が1mなので、それに近づけておく
	//===== 刻みを曲がりに合わせる =====
	// 刻みがそのまま折り目になる。
	// 半径5mを1m刻みで回ると、1区間で約11度曲がるので角が見える。
	//
	// かといって全部を細かくすると、直線に無駄な頂点が並ぶ。
	// 1500mの道を0.3m刻みにすると5000点。直線区間では意味がない。
	//
	// 「1区間で何度まで曲がってよいか」を決めて、
	// そこから刻みを逆算する。直線では粗く、ヘアピンでは細かくなる。

	// 1区間で許す曲がり(度)。
	// 小さいほど滑らかだが、点が増える。3度ならほぼ角が見えない
	constexpr float StepMaxTurnDeg = 3.0f;

	// 刻みの上限(m)。直線でもこれ以上は空けない。
	// 空けすぎると、坂の変化や地形の削りが飛び飛びになる
	constexpr float StepMax = 3.0f;

	// 刻みの下限(m)。
	// 細かくしすぎると、点の数が跳ね上がって作り直しが重くなる
	constexpr float StepMin = 0.25f;

	// 幅方向の分割数(片側)。
	// 中央の盛り上がりと路肩の落ち込みが表現できればよい
	// 中央の盛り上がりと路肩の落ち込みを、角を見せずに出す。
	// 粗いと断面が多角形に見える
	constexpr int WidthSegments = 6;

	//===== 制御点 =====
	// 制御点を置くファイル。
	// テキストで持つのは、手で開いて直せるようにするため。
	//   x y z  を1行に1点
	constexpr const char* PathFile = "Asset/Data/terrain/road_path.txt";

	// 制御点の最小数。これを下回ると道にならない
	constexpr int MinPoints = 4;

	//===== 縦断(道の高さ) =====
	// 道の高さは道が決める。地形からは取らない。
	//
	// 地形の高さをなぞると、道が地面の起伏をそのまま拾って
	// 上下する。実際の道は勾配に制限があり、山を削り谷を埋めて
	// 一定の傾きに収めてある。なぞった線は道に見えない。
	//
	// 制御点に高さが書いてあればそれを使う。
	// 書いていなければ地形から下敷きを作り、そこから均して
	// 勾配の上限に収める。

	// 勾配の上限。1進んだときに上下できる量。
	// 峠でも12%(約7度)を超える所は少ない。
	// 緩くしすぎると壁のような坂ができ、きつくしすぎると平坦になる
	constexpr float MaxGrade = 0.094f;

	// 道全体の持ち上げ(m)。
	//
	// 地形へ埋まりがちなときに、道ごと上げる。
	// 地形の削りも同じ高さで追うので、道と地形の関係は崩れない。
	//
	// 上げるほど盛り土が増え、切り通しが減る。
	// 山肌に貼り付いた道から、尾根を渡る道へ寄っていく
	constexpr float Lift = 7.05f;

	//===== 横断(左右の傾き) =====
	// 縦断で坂の傾きを扱うのと同じことを、左右にもやる。
	//
	// 中心線の高さだけを決めると、路面は常に水平になる。
	// 山肌を横切る道が水平のままだと、片側だけ盛り土が高く積まれ、
	// 反対側は切り立った崖になる。実際の道は山側へ少し傾いている。
	//
	// 傾けると、ドリフトでは走りそのものが変わる。
	// カントの付いたコーナーは、荷重が乗って角度を保ちやすい。

	// 地形の傾きにどれだけ追従するか。
	//   0 … 常に水平
	//   1 … 地形の傾きをそのまま拾う
	// 拾いすぎると路面が暴れるので、半分程度から始める
	constexpr float BankFollow = 1.50f;

	// 傾きの上限(高さ÷距離)。
	// 実際の道の片勾配は10%(約6度)まで。
	// 山肌に沿う道はもう少し傾くので、少し広く取る
	constexpr float MaxBank = 0.055f;

	// 傾きを均す回数。
	// 地形の細かい凹凸を拾うと、路面が小刻みに捻れる
	constexpr int   BankSmoothPasses = 40;

	// 傾きを測るときに、中心から左右どれだけ離れた所を見るか(m)。
	// 路肩の外まで取らないと、削った跡の平らな所だけを見てしまう
	constexpr float BankProbe = 12.0f;

	// 勾配を収めるための繰り返し回数。
	// 1回では行き渡らない。多いほど平らへ寄る
	constexpr int GradePasses = 200;

	// 下敷きを作るときの均し回数。
	// 地形の細かい凹凸を落とす。勾配の制限とは別に要る
	constexpr int SeedSmoothPasses = 24;

	// 制御点に高さが書かれているとみなす境目(m)。
	// 仮の道は高さ0で置いてあるので、それと区別する
	constexpr float AuthoredHeightEps = 0.01f;

	//===== 地形を沿わせる =====
	// 中心線は地形の凹凸を均してあるので、そのままだと
	// 下げた区間で道が地形の中へ潜り、上げた区間で宙に浮く。
	//
	// 道の周りの地形を、道の高さへ寄せる。
	// 実際の峠も切り土と盛り土で作られているので、これが本来の形。

	// 道の高さへ完全に合わせる幅(m)。中心からの距離。
	// 路肩の外まで含めておかないと、縁で地形が飛び出す
	constexpr float DeformInner = 1.0f;

	// そこから元の地形へ戻していく幅(m)。
	// 短いと崖になり、長いと山が削れすぎる
	constexpr float DeformOuter = 23.0f;

	// 削るのを許す深さ(m)。切り通しの深さの上限。
	// 制限しないと、尾根を突っ切る所で山が丸ごと消える
	constexpr float DeformCutMax = 19.5f;

	// 盛るのを許す高さ(m)。谷を渡る所の上限。
	// 超える所は、本来なら橋を架ける
	constexpr float DeformFillMax = 10.5f;

	// 路面の下に地形を敷く深さ(m)。
	//
	// 道の真下だけ。縁では路面と高さを合わせるので、
	// ここは「見えない所をどれだけ掘るか」でしかない。
	//
	// 深いほど、マス目の間の直線が路面を突き抜ける余地が減る
	constexpr float BedDrop = 2.0f;

	// 地形と路面の高さを合わせる境目(m)。中心からの距離。
	//
	// ここより内側は路面の下へ掘り、外側は路面の縁の高さから
	// 元の地形へ戻していく。
	//
	// 平らな床の上に道を置くと、縁に段差ができて
	// そこから地形が顔を出す。縁で高さを合わせれば段差が無くなる
	constexpr float MatchEdge = HalfWidth + ShoulderWidth;

	// 真下から外へ、盛り土の裾を下ろす角度(高さ÷距離)。
	//
	// 垂直に切り落とすと壁になる。実際の盛り土は
	// 安定する角度まで裾を広げてある。
	// 1.5:1(約34度)は土の安息角に近い
	constexpr float FillSlope = 0.66f;

	//===== 削ったあとの均し =====
	// 削り終えた地形を、道の周りだけもう一度均す。
	//
	// ■ なぜ要るか
	// 寄せる強さは中心線からの距離で決まるが、その距離は
	// 刻み(StepLength)ごとの点までの距離で測っている。
	//
	// 点と点の間では距離がわずかに大きくなるので、
	// 寄せる強さが刻みの周期で上下する。
	// 道に沿って細かい波が乗るのはこれが理由。
	//
	// 削ったあとに均せば、その波が消える。
	// 元の地形まで均すと山が丸くなるので、触った所だけにする。

	// 均す回数。多いほど滑らかだが、切り通しの角も丸くなる
	constexpr int DeformSmoothPasses = 3;

	// 均しをかける範囲。DeformOuter に対する割合。
	// 外側まで均すと、削っていない地形との境目が動いて
	// そこに新しい段差ができる
	constexpr float DeformSmoothRange = 0.85f;

	//===== 当たり判定 =====
	// 道からこの距離まで離れたら「道の外」とみなす(m)。
	// 路肩の外側に少し余裕を持たせる
	constexpr float EdgeMargin = 0.4f;

	// 投影の探索で、1つの区間を何分割して調べるか。
	//
	// ここで大まかな位置を出して、そのあと詰める。
	// 分割だけで精度を出そうとすると回数が増えるので、
	// 粗く探して細かく詰めるほうが速い
	constexpr int ProjectSamples = 12;

	// 大まかな位置を詰める回数。
	//
	// 分割だけだと、全長1430mを184点で見ることになり、
	// 約8mおきにしか位置が決まらない。
	// 車が道のどこに居るかが8m刻みでは、コーナーで
	// 横のずれが数メートル狂う。
	//
	// 見つけた点の前後を半分ずつ狭めていけば、
	// 20回でミリ単位まで詰まる
	constexpr int ProjectRefine = 30;

	//===== 見た目 =====
	// 素材を貼るまでの仮の色。
	// 地形と見分けが付く程度に暗くする
	constexpr float SurfaceR = 0.13f;
	constexpr float SurfaceG = 0.13f;
	constexpr float SurfaceB = 0.14f;

	// 素材のUVが1周する長さ(m)。
	// 短いと繰り返しが見えて、長いと解像度が落ちる
	constexpr float UvLength = 8.0f;
}
