#pragma once

// スプラインで作る道の定数。
//
// ■ なぜ地形と別に持つか
// 高さマップは真上から見た一枚の格子なので、
// 幅6mの道の断面(カントや中央の盛り上がり)を表現できない。
// 5mメッシュを1mへ上げても足りない。
//
// ドリフトではカントが効くので、そこが潰れるのは痛い。
//
// ■ 当たり判定はメッシュを見ない
// 位置をスプラインへ投影すれば、道のどこを走っているかが出る。
// そこから断面を評価すれば、高さと法線が厳密に求まる。
//
// 面を1枚ずつ調べるより速く、しかも正確。
// サスペンションを入れたときに、この差が効いてくる。
namespace RoadConst
{
	//===== 形 =====
	// 路面の幅(m)。片側の半分。全幅はこの2倍
	constexpr float HalfWidth = 3.5f;

	// 路肩の幅(m)。路面の外側に付ける、少し落ちた面。
	// ここまでは走れるが、グリップが落ちる想定
	constexpr float ShoulderWidth = 1.2f;
	// 路肩の落ち込み(m)
	constexpr float ShoulderDrop = 0.12f;

	// 路面中央の盛り上がり(m)。水はけのための形。
	// 少しでも入れると、轍に沿う感じが出る
	constexpr float Crown = 0.05f;

	//===== エプロン(地形へ溶ける裾) =====
	// 道の外側へ広げる面。
	//
	// ■ なぜ要るか
	// 地形は格子(1m四方)で、道は曲がった帯。格子は道の縁に沿えないので、
	// 地形だけで道の境目を作ると、必ず階段状になる。
	// どれだけ削り方を工夫しても、格子である限り消えない。
	//
	// 道からメッシュを生やせば、境目がスプラインの縁になる。
	// 曲がりに沿うので滑らかで、外端の高さを地形へ合わせれば繋がる。
	//
	// ■ 何をしているか
	// 路肩の外から、地形の高さへ向けて降りていく面を張る。
	// 内側は路面の縁の高さ、外側は地形そのものの高さ。
	// 見える境目は、格子ではなくこの面の外端になる。

	// 路肩の外に、道と平行に伸ばす幅(m)。
	//
	// 路肩の外端からいきなり地形へ落とすと、道が細い板に見える。
	// 実際の道は、縁の外にしばらく平場があってから法面が始まる。
	//
	// ここは路面の面をそのまま伸ばすので、カントも続く。
	// 「平ら」ではなく「道と平行」
	constexpr float ApronFlat = 1.6f;

	// 触りながら決めるときの上限(m)。
	// 平場は走る場所ではないが、峠だと待避所ぶんの幅が要ることがある
	constexpr float ApronFlatMax = 20.0f;

	// 平場を広げたぶん、斜面の降りる先も外へ伸ばす割合。
	//
	// 平場だけ伸ばすと、降りる先はそのままなので
	// 同じ幅でより深い所まで降りることになり、斜面が立つ。
	//
	// 1.0 で「広げた量と同じだけ斜面も伸びる」。
	// 0 で今までどおり(斜面は伸びない)
	constexpr float ApronFollowFlat = 1.0f;
	constexpr float ApronFollowMax  = 3.0f;

	// そこから地形へ溶けるまでの幅(m)。
	// 広いほど滑らかに溶けるが、道が太って見える
	constexpr float ApronWidth = 7.0f;

	// 裾ぜんたいの幅(m)。平場と法面の合計
	constexpr float ApronTotal = ApronFlat + ApronWidth;

	// 制御点ごとに指定できる裾の幅の上限(m)。
	// 区間ごとに伸ばせるようにしたので、既定より広げられる
	constexpr float ApronWidthMax = 40.0f;

	// 裾の外端から、真下へ伸ばす長さ(m)。
	//
	// 地形の格子は裾の縁に沿えないので、境目は必ず少しずれる。
	// 上から見えない壁を垂らしておけば、隙間があっても
	// 向こう側が透けない。
	//
	// 沈めるより確実。沈めると、傾いた地形では別の所が浮く
	constexpr float ApronSkirt = 2.0f;

	//===== 道の下の地形を描かない =====
	// 裾と地形が同じ高さで広く重なるので、遠くでどちらが手前か
	// 決まらなくなってちらつく。テクスチャを貼ると、
	// 模様が入れ替わって見えるのでもっと目立つ。
	//
	// 完全に隠れている地形の四角は、そもそも張らない。
	// 削り(切り土・盛り土)は今までどおり。消すのは描く三角だけ。
	//
	// 控えめに開ける。裾は折り返しの判定で落ちることがあるので、
	// ぎりぎりまで開けると、両方無くなって空が見える
	constexpr float CoverMargin = 1.5f;   // マス目いくつぶん内側に寄せるか

	// 高さを焼き戻すときに、縦に近い面を外す境目。
	// 面の法線の上向き成分。裾の外端の壁がこれに当たる
	constexpr float BakeUpMin = 0.30f;

	// 曲がりを見るときに、前後をどれだけ離すか(m)。
	//
	// 近すぎると刻みの揺れを拾って符号が暴れる。
	// 遠すぎるとヘアピンが均されて、曲がりが無いことになる
	constexpr float TurnSampleDist = 5.0f;

	//===== 裾どうしが重なるとき =====
	// ヘアピンや九十九折りでは、行きと帰りの道が近づく。
	// 裾を伸ばすほど、向かい合った裾どうしが重なる。
	//
	// 重なったぶんを消すと、間に地形が覗いて溝になる。
	// 代わりに、互いの真ん中で止める。
	//
	// 両方とも外端では地形の高さに寄せてあるので、
	// 真ん中で出会えば高さも揃う。1枚の面として繋がる。

	// 相手を探すとき、これより手前は「自分」とみなす(m)。
	// 見ないと、すぐ前後の断面を相手だと思って幅が潰れる
	constexpr float MergeIgnoreS = 40.0f;

	// 真ん中で止めるときの余白(m)。
	// ちょうどで合わせると、どちらの面が手前か決まらずちらつく
	constexpr float MergeGap = 0.15f;


	// 幅方向の分割数。
	//
	// 地形の起伏を拾うので、粗いと外端が地形から浮く。
	// 地形が1mマスなので、7mの裾なら7分割では足りない
	constexpr int   ApronSegments = 14;

	// 外端をどれだけ地形へ埋めるか(m)。
	// ちょうどに合わせると、どちらが手前か決まらずちらつく。
// 裾の外端を、地形からどれだけ持ち上げるか(m)。
	//
	// 道の下の地形は張らないが、地形の格子は裾の縁に沿えないので、
	// 縁に掛かる四角だけは残る。その輪と裾が同じ高さだと、
	// どちらが手前か決まらずちらつく。
	//
	// 沈めると地形が勝って、裾を横切る線が出る。
	// 持ち上げれば裾が勝つ。段差は外端の壁が隠す
	constexpr float ApronLift = 0.12f;

	//===== 裾が路面から離れてよい高さ =====
	// 道のすぐ横に高い山があると、裾はその斜面の高さへ向かって伸びる。
	// 途中は山の中を通り、先だけ表へ出るので、そこがちらつく。
	//
	// 離れすぎた所は面を落とす。穴埋めが縁を塞ぐので、
	// 裾は山にぶつかった所で終わる。
	//
	// 上と下で分ける。切り通しの壁を高く登る必要はないが、
	// 盛り土は谷底まで降りることがある
	constexpr float ApronMaxRise = 6.0f;    // 路面より上へ(m)
	constexpr float ApronMaxDrop = 30.0f;   // 路面より下へ(m)

	// 触りながら決めるときの上限
	constexpr float ApronRiseMax = 80.0f;

	//===== ヘアピン =====
	// 曲がりの半径より外へ出した点は、前後の断面で追い越し合って
	// 面が裏返る。半径5mのコーナーで中心から6m外へ出せば、
	// その点は曲がりの中心を通り越して、進む向きと逆へ動く。
	//
	// 幅を絞って逃げる手も試したが、道の幅が変わってしまう。
	// 走る道の幅は設計値であって、地形の都合で細くしてよいものではない。
	//
	// いまは飛び出した頂点を落として、跡を塞いでいる(HjRoad.cpp)。
	// 判定は頂点の動く向きで直接見るので、しきい値が要らない。

	//===== 裾の幅を詰める =====
	// 裾は路面より外(中心から11.7m)まで伸びるので、
	// 折り返しの判定に引っかかるのが路面よりずっと早い。
	// 半径15mで 1 - 11.7/15 = 0.22 と、もう潰れかけている。
	//
	// このコースは半径15m未満が359mあり、そこで裾が途中まで削られ、
	// 地形へ届かないまま切り落とされていた。
	//
	// 裾の仕事は地形へ繋ぐことなので、切って途中で終わらせるより、
	// 幅を詰めてでも地形まで届かせるほうがよい。
	// 路面と違って裾の幅は設計値ではない。
	//
	// これを下回る幅しか取れないなら、裾は出さない(m)
	constexpr float ApronMinWidth = 0.5f;

	// 幅を前後どこまで見て決めるか(m)。
	//
	// その場の半径だけで決めると、隣り合う断面で幅が 0m→7m と飛ぶ。
	// 断面の間隔は0.25mしかないので、裾が一点に潰れて
	// そこへ十数枚の三角が集まる。ワイヤーで見ると扇になる。
	//
	// 前後を見て一番狭い所に合わせておけば、手前から細くなり始める
	constexpr float ApronLookAhead = 5.0f;

	// 幅を均す回数。最小を取るだけだと境目が階段になる
	constexpr int ApronSmoothPasses = 10;

	//===== 断面どうしの交差 =====
	// 断面は曲がりの中心へ向かって集まる。
	// ヘアピンでは、入口の断面と出口の断面が、
	// 遠く離れているのに交差する。
	//
	// 前後の断面だけを見る判定では、その遠い交差を捉えられない。
	// 実測で1307個の頂点が見逃されていた。
	//
	// 交差していない点は、中心線までの距離が
	// 中心からのずれにちょうど等しい。近ければ入り込んでいる。

	// どれだけ近ければ交差とみなすか。
	// 中心線を折れ線で近似しているぶんの誤差を見込む
	constexpr float CrossTol = 0.10f;

	// これより中心に近い所は見ない(m)。
	// 中心線のすぐそばは、刻みの粗さで誤判定になる
	constexpr float CrossIgnore = 0.5f;

	//===== 潰れた面を捨てる =====
	// 折り返しは、いきなり裏返るのではなく、じわじわ潰れて起きる。
	//
	// 中心から距離 o の点は、曲がりの半径 R に対して
	// 中心線の (1 - o/R) 倍しか進まない。
	// o が R に近づくほど、その列は前へ進まなくなる。
	//
	// 「逆を向いたら捨てる」だけだと、進み方が中心線の1%といった
	// ほぼ潰れた面が残る。細長い棘になって、法線も出ない。
	//
	// 中心線に対してこれだけ進んでいなければ捨てる
	constexpr float MinAdvance = 0.2f;

	//===== ミター接合 =====
	// 断面を「その場の接線に直交」させて置くと、角の所で
	// 隣り合う区間の平行線がぴたりと交わらず、幅がわずかに足りなくなる。
	// 実測で、ずれは中央1.6mm・最大91mm。
	//
	// 二等分線の向きに置いて 1/cos(θ/2) だけ伸ばすと、
	// 平行線どうしが交点で出会う。ずれは0になる。
	//
	// 急な角では 1/cos(θ/2) が跳ね上がって棘になるので、
	// 伸びに上限を置く。SVGなどの線の描き方でも同じ制限がある
	constexpr float MiterLimit = 2.0f;

	//===== 刻みを曲がりに合わせる =====
	// 刻みがそのまま折り目になる。
	// 半径5mを1m刻みで回ると、1区間で約11度曲がるので角が見える。
	//
	// かといって全部を細かくすると、直線に無駄な頂点が並ぶ。
	// 1500mの道を0.3m刻みにすると5000点。直線区間では意味がない。
	//
	// 「1区間で何度まで曲がってよいか」を決めて、
	// そこから刻みを逆算する。直線では粗く、ヘアピンでは細かくなる。

	// 1区間で許す曲がり(度)。
	// 小さいほど滑らかだが、点が増える。3度ならほぼ角が見えない
	constexpr float StepMaxTurnDeg = 3.0f;

	// 刻みの上限(m)。直線でもこれ以上は空けない。
	// 空けすぎると、坂の変化や地形の削りが飛び飛びになる
	constexpr float StepMax = 3.0f;

	// 刻みの下限(m)。
	// 細かくしすぎると、点の数が跳ね上がって作り直しが重くなる
	constexpr float StepMin = 0.25f;

	// どこまで先を見て刻みを決めるか(m)。
	//
	// その場の曲率だけで前へ進めると、直線からヘアピンへ入るとき
	// 直線の刻み(3m)のままカーブへ飛び込む。
	// 出るときは細かいままなので、制御点を境に密度が食い違う。
	//
	// 実測で、制御点の前後10mの刻みの比が最大4.4倍あった。
	// 手前から見ておけば、カーブに入る前から細くなり始める
	constexpr float StepLookAhead = 6.0f;

	// 先を見る回数と、見る点の数。
	// 刻みを決めるのに刻みが要るので、何度か回して寄せる
	constexpr int StepPasses = 3;
	constexpr int StepProbes = 10;

	// 刻みが広がってよい倍率。
	//
	// 狭まるのは安全なので即座に。広がるのは徐々に。
	// いきなり広げると、カーブを出た所で三角の形が跳ねる
	constexpr float StepGrowth = 1.1f;

	// 幅方向の分割数(片側)。
	// 中央の盛り上がりと路肩の落ち込みが表現できればよい
	// 中央の盛り上がりと路肩の落ち込みを、角を見せずに出す。
	// 粗いと断面が多角形に見える
	constexpr int WidthSegments = 6;

	//===== 制御点 =====
	// 制御点を置くファイル。
	// テキストで持つのは、手で開いて直せるようにするため。
	//   x y z  を1行に1点
	constexpr const char* PathFile = "Asset/Data/terrain/road_path.txt";

	// 制御点の最小数。これを下回ると道にならない
	constexpr int MinPoints = 4;

	//===== 縦断(道の高さ) =====
	// 道の高さは道が決める。地形からは取らない。
	//
	// 地形の高さをなぞると、道が地面の起伏をそのまま拾って
	// 上下する。実際の道は勾配に制限があり、山を削り谷を埋めて
	// 一定の傾きに収めてある。なぞった線は道に見えない。
	//
	// 制御点に高さが書いてあればそれを使う。
	// 書いていなければ地形から下敷きを作り、そこから均して
	// 勾配の上限に収める。

	// 勾配の上限。1進んだときに上下できる量。
	// 峠でも12%(約7度)を超える所は少ない。
	// 緩くしすぎると壁のような坂ができ、きつくしすぎると平坦になる
	constexpr float MaxGrade = 0.094f;

	// 道全体の持ち上げ(m)。
	//
	// 地形へ埋まりがちなときに、道ごと上げる。
	// 地形の削りも同じ高さで追うので、道と地形の関係は崩れない。
	//
	// 上げるほど盛り土が増え、切り通しが減る。
	// 山肌に貼り付いた道から、尾根を渡る道へ寄っていく
	constexpr float Lift = 7.05f;

	//===== 横断(左右の傾き) =====
	// 縦断で坂の傾きを扱うのと同じことを、左右にもやる。
	//
	// 中心線の高さだけを決めると、路面は常に水平になる。
	// 山肌を横切る道が水平のままだと、片側だけ盛り土が高く積まれ、
	// 反対側は切り立った崖になる。実際の道は山側へ少し傾いている。
	//
	// 傾けると、ドリフトでは走りそのものが変わる。
	// カントの付いたコーナーは、荷重が乗って角度を保ちやすい。

	// 地形の傾きにどれだけ追従するか。
	//   0 … 常に水平
	//   1 … 地形の傾きをそのまま拾う
	// 拾いすぎると路面が暴れるので、半分程度から始める
	constexpr float BankFollow = 1.50f;

	// 傾きの上限(高さ÷距離)。
	// 実際の道の片勾配は10%(約6度)まで。
	// 山肌に沿う道はもう少し傾くので、少し広く取る
	constexpr float MaxBank = 0.055f;

	// 傾きを均す回数。
	// 地形の細かい凹凸を拾うと、路面が小刻みに捻れる
	constexpr int   BankSmoothPasses = 40;

	// 傾きを測るときに、中心から左右どれだけ離れた所を見るか(m)。
	// 路肩の外まで取らないと、削った跡の平らな所だけを見てしまう
	constexpr float BankProbe = 12.0f;

	// 勾配を収めるための繰り返し回数。
	// 1回では行き渡らない。多いほど平らへ寄る
	constexpr int GradePasses = 200;

	// 下敷きを作るときの均し回数。
	// 地形の細かい凹凸を落とす。勾配の制限とは別に要る
	constexpr int SeedSmoothPasses = 24;

	// 制御点に高さが書かれているとみなす境目(m)。
	// 仮の道は高さ0で置いてあるので、それと区別する
	constexpr float AuthoredHeightEps = 0.01f;

	//===== 地形を沿わせる =====
	// 中心線は地形の凹凸を均してあるので、そのままだと
	// 下げた区間で道が地形の中へ潜り、上げた区間で宙に浮く。
	//
	// 道の周りの地形を、道の高さへ寄せる。
	// 実際の峠も切り土と盛り土で作られているので、これが本来の形。

	// 道の高さへ完全に合わせる幅(m)。中心からの距離。
	// 路肩の外まで含めておかないと、縁で地形が飛び出す
	constexpr float DeformInner = 1.0f;

	// そこから元の地形へ戻していく幅(m)。
	// 短いと崖になり、長いと山が削れすぎる
	constexpr float DeformOuter = 23.0f;

	// 削るのを許す深さ(m)。切り通しの深さの上限。
	// 制限しないと、尾根を突っ切る所で山が丸ごと消える
	constexpr float DeformCutMax = 19.5f;

	// 盛るのを許す高さ(m)。谷を渡る所の上限。
	// 超える所は、本来なら橋を架ける
	constexpr float DeformFillMax = 10.5f;

	// 路面の下に地形を敷く深さ(m)。
	//
	// 道の真下だけ。縁では路面と高さを合わせるので、
	// ここは「見えない所をどれだけ掘るか」でしかない。
	//
	// 深いほど、マス目の間の直線が路面を突き抜ける余地が減る
	constexpr float BedDrop = 2.0f;

	// 地形と路面の高さを合わせる境目(m)。中心からの距離。
	//
	// ここより内側は路面の下へ掘り、外側は路面の縁の高さから
	// 元の地形へ戻していく。
	//
	// 平らな床の上に道を置くと、縁に段差ができて
	// そこから地形が顔を出す。縁で高さを合わせれば段差が無くなる
	constexpr float MatchEdge = HalfWidth + ShoulderWidth;

	// 真下から外へ、盛り土の裾を下ろす角度(高さ÷距離)。
	//
	// 垂直に切り落とすと壁になる。実際の盛り土は
	// 安定する角度まで裾を広げてある。
	// 1.5:1(約34度)は土の安息角に近い
	constexpr float FillSlope = 0.66f;

	//===== 削ったあとの均し =====
	// 削り終えた地形を、道の周りだけもう一度均す。
	//
	// ■ なぜ要るか
	// 寄せる強さは中心線からの距離で決まるが、その距離は
	// 刻み(StepLength)ごとの点までの距離で測っている。
	//
	// 点と点の間では距離がわずかに大きくなるので、
	// 寄せる強さが刻みの周期で上下する。
	// 道に沿って細かい波が乗るのはこれが理由。
	//
	// 削ったあとに均せば、その波が消える。
	// 元の地形まで均すと山が丸くなるので、触った所だけにする。

	// 均す回数。多いほど滑らかだが、切り通しの角も丸くなる
	constexpr int DeformSmoothPasses = 3;

	// 均しをかける範囲。DeformOuter に対する割合。
	// 外側まで均すと、削っていない地形との境目が動いて
	// そこに新しい段差ができる
	constexpr float DeformSmoothRange = 0.85f;

	//===== 当たり判定 =====
	// 道からこの距離まで離れたら「道の外」とみなす(m)。
	// 路肩の外側に少し余裕を持たせる
	constexpr float EdgeMargin = 0.4f;

	// 投影の探索で、1つの区間を何分割して調べるか。
	//
	// ここで大まかな位置を出して、そのあと詰める。
	// 分割だけで精度を出そうとすると回数が増えるので、
	// 粗く探して細かく詰めるほうが速い
	constexpr int ProjectSamples = 12;

	// 大まかな位置を詰める回数。
	//
	// 分割だけだと、全長1430mを184点で見ることになり、
	// 約8mおきにしか位置が決まらない。
	// 車が道のどこに居るかが8m刻みでは、コーナーで
	// 横のずれが数メートル狂う。
	//
	// 見つけた点の前後を半分ずつ狭めていけば、
	// 20回でミリ単位まで詰まる
	constexpr int ProjectRefine = 30;

	//===== 見た目 =====
	// 素材を貼るまでの仮の色。
	// 地形と見分けが付く程度に暗くする
	// 頂点の色へ詰める。
	//
	// 路面と裾で色を変えたいが、材質を分けるとメッシュを1枚にできない。
	// 分けると境目の穴埋めが相手側へ届かず、穴が残る。
	// シェーダが頂点カラーを掛けているので、そちらに持たせる
	constexpr unsigned int PackColor(float r, float g, float b)
	{
		// ABGR の並び
		return 0xFF000000u
		     | (static_cast<unsigned int>(b * 255.0f) << 16)
		     | (static_cast<unsigned int>(g * 255.0f) << 8)
		     |  static_cast<unsigned int>(r * 255.0f);
	}

	constexpr float SurfaceR = 0.13f;
	constexpr float SurfaceG = 0.13f;
	constexpr float SurfaceB = 0.14f;

	// 素材のUVが1周する長さ(m)。
	// 短いと繰り返しが見えて、長いと解像度が落ちる
	constexpr float UvLength = 8.0f;
}
