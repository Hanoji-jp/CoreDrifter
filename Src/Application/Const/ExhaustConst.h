#pragma once

// 排気系(管・集合部・マフラー)の共鳴の定数。
//
// これまでマフラーを共鳴フィルタ1個で近似していたが、それが
// 「声っぽく聞こえる」原因だった。倍音の豊かな音に鋭い共鳴を1つ立てる構造は、
// 物理的に人間の母音とまったく同じだからである。
//
// 実物の排気系には共鳴が何十個もある。
//   ・管の長さで決まる複数のモード(1次, 3次, 5次...)
//   ・集合部や膨張室の共鳴
//   ・サイレンサー内部の反射
// これらが重なることで、はじめて「管を通った音」になる。
//
// engine-simがインパルス応答の畳み込みでやっているのがこれで、
// ここでは共鳴モードの並列(モーダル合成)で近似する。
// 畳み込みより軽く、管の長さから周波数を決められるので調整もしやすい。
namespace ExhaustConst
{
	constexpr float SpeedOfSound = 343.0f;   // 音速(m/s)

	// 共鳴モードの数。多いほど「管の中で音が転げ回る」感じが出る。
	// 少ないと個々の共鳴が聞き分けられてしまい、母音に近づく。
	constexpr int   ModeCount = 16;

	// 排気管の長さ(m)。片側が開いた管なので、共鳴は奇数次に立つ。
	//   f(n) = (2n-1) × 音速 ÷ (4 × 管長)
	// 長いほど基本のモードが低くなり、低く唸る。
	constexpr float PipeLength = 2.4f;

	// モードの周波数を少しずらす量(0=完全な奇数次)。
	// 綺麗な整数比のまま並べると倍音列と同じになり、音程が立ってしまう。
	// 実物の排気系は管も部屋も形が不揃いなので、比は綺麗にならない。
	constexpr float ModeDetune = 0.06f;

	// 各モードの帯域幅(Hz)。狭いほど長く響き、広いほど短く収まる。
	// 狭すぎると個々の共鳴が「鳴き」として聞こえて母音に寄る。
	constexpr float ModeBandwidth    = 55.0f;
	// 高いモードほど速く減衰する(高音ほど早く失われる実際の性質)
	constexpr float ModeBandwidthRise = 22.0f;

	// 高いモードほど弱くする量。大きいほど丸くこもった音
	constexpr float ModeRolloff = 0.85f;

	// 最低次のモードを抑える強さ。
	// 1/nで並べると1次(2.4mで約36Hz)が一番強くなるが、
	// 実物の管では最低次ほど強く減衰する。そのまま鳴らすと
	// 100〜180Hzが張り出して「ドコドコ」＝トラクターのような音になる。
	constexpr float LowModeCut   = 0.75f;   // 0=抑えない
	constexpr float LowModeCutHz = 260.0f;  // この周波数より下を抑える

	// 共鳴音をどれだけ混ぜるか(0=素の圧力波形のまま)
	constexpr float ResonanceMix = 0.80f;

	// 全体の音量調整。モードを足し合わせるぶん大きくなるので下げる
	constexpr float OutputTrim = 0.55f;
}
