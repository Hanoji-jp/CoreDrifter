#pragma once

// エンジンの物理シミュレーション(音を作るため)の定数。
//
// 気筒の中の圧力を毎サンプル解いて、排気管へ吹き出す流れを音にする。
// 倍音を並べる合成と違い、波形は「その瞬間の圧力」から出てくるので、
// 回転数やアクセル開度で音の形そのものが変わる。
//
//   クランク角 → シリンダー容積 V(θ)
//   断熱変化   → P・V^γ = 一定
//   点火       → 圧力が跳ね上がる(吸入量＝アクセル開度に比例)
//   排気弁開   → 圧力差に応じて排気管へ吹き出す
//   排気管の圧力変化 → その微分が音
//
// ※クランク・ピストンの剛体シミュレーションは作らない。
//   車の駆動系(CarBase)から回転数を貰えるので、エンジンが生むトルクは要らない。
namespace EngineSimConst
{
	//===== クランク・シリンダー =====
	constexpr float CycleDeg = 720.0f;   // 4ストロークはクランク2回転で1サイクル

	// 圧縮比。容積の最小(上死点)と最大(下死点)の比。
	// 高いほど爆発前の圧力が高く、パンチのある音になる。
	constexpr float CompressionRatio = 9.5f;

	//===== 行程のタイミング(クランク角) =====
	// 0度=吸気上死点。720度で1サイクル。
	//   0〜180   吸気
	//   180〜360 圧縮
	//   360〜540 燃焼・膨張
	//   540〜720 排気
	// 実機の弁は行程の境目ちょうどではなく、前後にずらして開く(バルブタイミング)。
	constexpr float IntakeOpenDeg   = 700.0f;  // 吸気弁が開く(上死点の少し前)
	constexpr float IntakeCloseDeg  = 220.0f;  // 閉じる(下死点の少し後)
	constexpr float ExhaustOpenDeg  = 500.0f;  // 排気弁が開く(下死点の手前＝ブローダウン)
	constexpr float ExhaustCloseDeg = 20.0f;   // 閉じる(上死点の少し後)

	// 点火時期(上死点の手前)。早いほど圧力のピークが鋭くなる
	constexpr float IgnitionDeg     = 345.0f;
	// 燃焼にかかるクランク角。短いほど「パンッ」と鋭い
	constexpr float BurnDurationDeg = 45.0f;

	//===== ピストンの幾何 =====
	// コンロッド比(コンロッド長 ÷ クランク半径)。
	// 単純な余弦でピストンを動かすのは、コンロッドが無限に長い場合の近似。
	// 実際は有限長なので、上死点側と下死点側で動きが非対称になり、
	// 圧力の波形もそれに従って歪む。この歪みが音の質感に出る。
	constexpr float RodRatio = 3.2f;

	//===== 気体 =====
	constexpr float Gamma = 1.32f;   // 比熱比。燃焼ガスは空気(1.4)より少し低い

	//===== 管(排気・吸気) =====
	// 管は「双方向の遅延線」で表す(デジタル導波管)。
	// 波は行きと帰りの2本を同時に走り、両端で反射する。
	//   出口側 … 断面が広がるので「負圧」として反射（位相が反転）
	//   根元側 … ほぼ全反射（位相はそのまま）
	// 両端で反射するから管の中に定在波ができ、管の長さで音程が決まる。
	// これが「排気の音程」の正体。
	//
	// ※管は気筒ごとではなく1本ずつ持つこと。
	//   気筒ごとに持たせると6気筒で排気と吸気の12本が同時に鳴り、
	//   混ざって濁った唸りになる。実際に耳へ届くのは集合部から先の
	//   1本と、吸気の入口までの1本で、響きはそこで決まる。
	constexpr float ExhaustPipeLength = 1.30f;  // 集合部から出口まで(m)
	constexpr float IntakePipeLength  = 0.42f;  // 吸気の弁から入口まで(m)
	constexpr float RunnerReflect = 0.28f;  // 出口で戻ってくる強さ(0=反射なし)
	constexpr float IntakeRunnerReflect = 0.25f;
	constexpr float ValveEndReflect = 0.55f; // 根元側の反射
	// 管の壁では高い成分から失われる。これが無いと金属的に鳴り続ける
	constexpr float RunnerDamp    = 0.55f;
	constexpr int   RunnerMaxDelay = 2048;  // 遅延バッファの長さ(サンプル)
	// 管へ入れる前に定常成分を落とす強さ。1に近いほど低い音まで残す。
	// 落とさないと管の固有振動が回転数と無関係に鳴り続ける
	constexpr float PipeDcBlock   = 0.9990f;

	constexpr float ColdSoundSpeed = 343.0f;     // 吸気は常温なので音速も常温
	constexpr float HotSoundSpeed  = 500.0f;     // 排気は高温なので音速が速い
	// 排気に対する吸気の混ぜ具合。
	// 排気だけで音を作ると、吸い込む側の音が丸ごと抜け落ちる。
	// NAの日本車で「吸気音」と呼ばれるのがこれ。
	constexpr float IntakeLevel    = 0.12f;

	//===== エンジン本体の機械音 =====
	// BeamNGはエンジン音と排気音を別のレイヤーとして混ぜている。
	// 排気だけだと「マフラーの音」しか鳴らず、本体から出ている音が無い。
	//
	// 主な発生源は弁の着座。カムに押された弁が座面へ戻る瞬間に当たる音で、
	// クランク角に同期して規則正しく出る。回転が上がるほど着座速度が上がり、
	// 強くなる。日本車のNAが「メカメカしい」と言われる音の正体。
	constexpr float MechLevel   = 0.12f;    // 混ぜ具合
	constexpr float MechHz      = 2600.0f;  // 当たる音の高さ
	constexpr float MechQ       = 3.0f;     // 鋭さ
	constexpr float MechRpmRef  = 3000.0f;  // この回転を基準に着座の強さを決める

	//===== 流れ(オリフィス) =====
	// 圧力差に比例して流すのは低速な流れの近似。
	// 実際の気体は音速で頭打ちになる(チョーク)。
	// 排気弁が開いた瞬間は圧力差が非常に大きく、必ずチョークするので、
	// 比例のままだと立ち上がりが鈍って「破裂」ではなく「吹き出し」になる。
	constexpr float ChokeRatio = 0.528f;   // これより圧力比が低いとチョーク(空気でほぼこの値)

	// 大気圧を1.0とした基準。実際の単位は使わず相対値で解く
	constexpr float AtmosPressure = 1.0f;
	// 燃焼で加わる圧力。吸入量に比例するので、アクセルを抜くと弱くなる
	constexpr float CombustionHeat = 26.0f;

	//===== 弁の流量 =====
	// 弁が開いている間、圧力差のどれだけの割合が「毎秒」流れるか。
	// サンプル単位で解くので、dt(=1/44100秒)を掛けて1サンプルぶんになる。
	// ここを小さくしすぎると、排気行程の間に圧力が抜けきらず、
	// 毎周期積み上がって飽和し、ずっと歪んだ音になる。
	// 6000rpmの排気行程は約300サンプルしかないので、その間に抜けきる大きさが要る。
	constexpr float ExhaustFlowRate = 900.0f;
	constexpr float IntakeFlowRate  = 500.0f;
	// アクセル全閉でも少しは空気が入る(そうしないとエンジンが止まった音になる)
	constexpr float IdleThrottle    = 0.06f;

	//===== 排気管(集合部) =====
	// 各気筒から吹き出した気体が集まる部屋。ここの圧力変化が音になる。
	constexpr float PlenumVolume   = 2.2f;   // 大きいほど圧力変化が緩やか＝こもる
	constexpr float PlenumOutflow  = 3.4f;   // 大気へ抜ける速さ。小さいと詰まって唸る

	//===== オーバーサンプリング =====
	// 排気弁が開いた瞬間の圧力変化は非常に鋭く、可聴上限をはるかに超える
	// 成分を含む。出力と同じ44.1kHzで直接解くと、それが折り返して
	// 非整数倍の金属的なノイズになる(エイリアシング)。
	// 回転が上がって波形が鋭くなるほど悪化するので、高回転が特に汚くなる。
	//
	// 対策：高いレートで解いてから、ローパスを通して落とす。
	// engine-simも同じ問題にアンチエイリアスフィルタで対処している。
	constexpr int   OverSample     = 4;        // 出力の何倍のレートで解くか
	constexpr float AntiAliasHz    = 15000.0f; // 落とす前に切る周波数

	//===== 出力 =====
	// 圧力そのものではなく「圧力の変化」が音。空気の疎密波は圧力の時間変化なので、
	// 微分を取るのが物理的に正しい(engine-simも同じことをしている)。
	//===== 自動レベル合わせ =====
	// 出力の大きさは気筒数・圧縮比・排気の抜け・管の長さなど、
	// ほぼ全部のパラメータで何倍にも動く。毎回手で合わせるのは現実的でなく、
	// 合っていないと出力段のソフトクリップが常時掛かって波形が矩形波になり、
	// エンジンのパルス感が消えて「ずっと鳴っている」音になる。
	//
	// ※実効値ではなく「山の高さ」で合わせること。
	//   実効値で合わせると、パルスの間の静けさが長いほど倍率が上がり、
	//   山だけが突き抜けて逆にうるさくなる。エンジン音は静けさの割合が
	//   回転数と気筒数で大きく変わるので、この違いが効く。
	constexpr float AutoLevelPeak    = 0.65f;  // 目標の山の高さ
	constexpr float PeakHoldSeconds  = 0.30f;  // 山を覚えておく時間
	// 追従の時定数(秒)。短いと吹け上がりの迫力まで潰してしまうので長めにする
	constexpr float AutoLevelSeconds = 1.5f;
	constexpr float AutoGainMax      = 500.0f;

	// 自動レベル合わせの後に掛ける微調整。1.0が基準
	constexpr float OutputGain = 1.0f;
	// 直流成分を抜くフィルタ。取らないと波形が上下どちらかへ寄って音量を食う
	constexpr float DcBlock = 0.9995f;
}
